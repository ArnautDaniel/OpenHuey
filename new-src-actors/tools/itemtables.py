#!/usr/bin/env python3
"""The items' classes read from the executable into scripts/items/tables.fs (src/game/items.c:
each item a class of its own on one of a few middle classes, whose small methods return
constants - Items_Give's kItemCtors, the vtables' +0x10 kind, +0x14 actions, +0x18 how it is
held, +0x1C its place in a sort, +0x28 its picture's file). Also the kinds' equipment slots
(kItemKindSlot).

usage: itemtables.py [repo root]"""
import os
import re
import struct
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..')
elf = open(os.path.join(root, 'baserom', 'SLUS_210.75'), 'rb').read()
ph, = struct.unpack_from('<I', elf, 0x1C)
n, = struct.unpack_from('<H', elf, 0x2C)
segs = [struct.unpack_from('<5I', elf, ph + i * 32)[1:] for i in range(n)]
syms = {}
for line in open(os.path.join(root, 'config', 'symbol_addrs.txt')):
    m = re.match(r'(\w+) = 0x([0-9A-Fa-f]+);', line)
    if m:
        syms[m.group(1)] = int(m.group(2), 16)


def rd(va, fmt='<I'):
    for off, vaddr, _, size in segs:
        if vaddr <= va < vaddr + size:
            return struct.unpack_from(fmt, elf, off + va - vaddr)[0]
    raise ValueError(hex(va))


def cstr(va):
    s = b''
    while rd(va, '<B'):
        s += bytes([rd(va, '<B')])
        va += 1
    return s.decode('latin1')


def run(fn):
    """A method's result: ('v0', constant), ('a1', the value given the call it makes), or None.
    Follows lui / addiu / ori into registers up to a return or a call."""
    r = [0] * 32
    pc = fn
    for _ in range(16):
        w = rd(pc)
        op, rs, rt, imm = w >> 26, (w >> 21) & 31, (w >> 16) & 31, w & 0xFFFF
        simm = imm - 0x10000 if imm & 0x8000 else imm

        def step(w):
            op, rs, rt, imm = w >> 26, (w >> 21) & 31, (w >> 16) & 31, w & 0xFFFF
            simm = imm - 0x10000 if imm & 0x8000 else imm
            if op == 0x0F:
                r[rt] = (imm << 16) & 0xFFFFFFFF
            elif op in (0x09, 0x19):
                r[rt] = (r[rs] + simm) & 0xFFFFFFFF
            elif op == 0x0D:
                r[rt] = r[rs] | imm
        if op == 0 and (w & 0x3F) == 0x08 and rs == 31:   # jr ra (and its delay slot)
            step(rd(pc + 4))
            return ('v0', r[2])
        if (op == 0 and (w & 0x3F) in (0x08, 0x09)) or op in (0x02, 0x03):   # a call (or a tail call)
            step(rd(pc + 4))
            return ('a1', r[5])
        step(w)
        pc += 4
    return None


def const(fn):
    x = run(fn)
    return x[1] if x and x[0] == 'v0' else None


def picture(fn):
    x = run(fn)
    if x and x[0] == 'a1' and x[1]:
        name = cstr(x[1])
        if name.endswith('.TEX'):
            return name[:-4].replace('\\', '/')
    return None


items = []
for i in range(0xAD):
    name = 'ItemClassF430_vtable' if i == 0x3F else 'Item%02X_vtable' % i
    if name not in syms:
        continue
    vt = syms[name]
    kind, acts, held, key = (const(rd(vt + o)) for o in (0x10, 0x14, 0x18, 0x1C))
    pic = picture(rd(vt + 0x28))
    items.append((i, kind, acts, held, key, pic))
slots = [rd(syms['kItemKindSlot'] + k, '<b') for k in range(10)]

out = []
w = out.append
w('\\ items/tables.fs - generated by tools/itemtables.py: the items\' classes from the executable')
w('\\ (src/game/items.c). A row per item id: its kind (the menu\'s icon, the equipment slot),')
w('\\ what can be done with it (1 use, 2 equip, 4 discard; $80000000 its note changes once it')
w('\\ is used), how it is held (0 one, 1 a stack, 2 a counter), its place in a sort. -1: no item.')
w('IN: items.tables')
w('USING: engine ;')
w('')
w('$AD constant #item-ids')
w('4 cells constant /item-info')
w('create item-info')
known = {i: (k, a, h, s) for i, k, a, h, s, _ in items}
for i in range(0xAD):
    k, a, h, s = known.get(i, (-1, 0, 0, 0))
    w('  %d , $%X , %d , $%X ,   \\ $%02X' % (k, a, h, s, i))
w('\\ the kinds\' equipment slots (-1 none): 4 boots, 5 earrings, 6 the costume, 9 the choker')
w('create kind-slots  ' + '  '.join('%d ,' % v for v in slots))
w('')
w('\\ its picture (ITEMnn/ITEM_xxx.TEX less the extension; 0 0 none)')
w(': item-picture ( id -- addr len )')
w('    case')
for i, k, a, h, s, pic in items:
    if pic:
        w('        $%02X of  s" %s"  endof' % (i, pic))
w('        >r 0 0 r>')
w('    endcase ;')
path = os.path.join(here, '..', 'scripts', 'items', 'tables.fs')
os.makedirs(os.path.dirname(path), exist_ok=True)
open(path, 'w').write('\n'.join(out) + '\n')
print('wrote', path, len(items), 'items')
