: hewie-controlled? ( -- flag )  false ;   \ (the Hewie-controlled sections: H4)

\ ---- waiting (an action script's turn ends, each frame) ----
: yield ( -- )  wait-frame ;
: frames? ( n -- flag )  self-frames @ $FFFF and = ;
: self-frames-reset ( -- )  0 self-frames ! ;
: self-wait-frames ( n -- )
    in-slot? 0= if  drop exit  then  begin  self-frames @ over < while  yield  repeat  drop ;
: self-wait-16 ( -- )  16 self-wait-frames ;

\ ---- actions: the action scripts in their slots (Event_StartAction, Events_GiveScript) ----
: scene-id? ( id -- flag )  $FF and $F0 $FB within ;
: slot-of ( id -- k )  $FF and $F0 - 6 + ;     \ (a scene's slot: 6..16)
: slot-task ( k -- addr )  cells slot-tasks + ;
: free-slot ( k -- )
    dup slot-task @ ?dup if  forth:kill  then
    0 over slot-task !  -1 over cells slot-who + !  -1 over cells slot-ids + !  0 swap cells slot-frames + ! ;
: free-slots ( -- )  #slots 0 do  i free-slot  loop ;
: fill-slot ( xt who id k -- )
    >r  r@ cells slot-ids + !  r@ cells slot-who + !  0 r@ cells slot-frames + !
    r@ slot-task @ ?dup if  forth:kill  then
    spawn-held r> slot-task ! ;
: start-action ( id act -- )   \ a scene script: its own slot, no character
    script-for ?dup 0= if  drop exit  then  swap  -1 swap  dup slot-of  fill-slot ;
: give-script ( cs act -- )   \ a character's: slot cs + 1, as itself
    script-for ?dup 0= if  drop exit  then  swap  dup  over 1+  fill-slot ;
: tell-scripted ( cs on -- )   \ (the character told: a script of the room has it, or lets go)
    swap char-actor dup 0< if  2drop exit  then  send scripted ;
: release ( cs -- )   \ (its script is over: free again)
    dup cells char-scripted + @ 0= if  drop exit  then
    0 over cells char-scripted + !  0 tell-scripted ;
: char-action ( cs act -- )
    over cells char-scripted + @ 0= if  over -1 tell-scripted  then
    -1 2 pick cells char-scripted + !  give-script ;
: start-for ( mode who act force -- )
    leaving @ if  2drop 2drop exit  then
    >r rot drop                                     ( who act )  ( R: force )
    over scene-id? if
        over slot-of slot-task @ 0=  r> or  if  start-action  else  2drop  then  exit
    then
    swap char-slot dup 0< if  2drop r> drop exit  then    ( act cs )
    swap  r> if  char-action exit  then
    over cells char-scripted + @ 0= if  char-action  else  2drop  then ;
: action ( mode who act -- )  false start-for ;
: action-force ( mode who act -- )  true start-for ;
: end-for ( who -- )
    dup scene-id? if  slot-of free-slot exit  then
    char-slot dup 0< if  drop exit  then
    dup release  1+ free-slot ;
: action-end ( who -- )  end-for ;
\ the script's character idle again (with none: the script ends) - its turn ends
: self-idle-or-end ( -- )
    in-slot? 0= if  exit  then
    self-char dup 0< 0= if
        dup release
        msg-owner @ = if  -1 msg-owner !  then
    else  drop  then
    ctx-slot @ free-slot ;   \ (the task is gone: nothing after this runs)
: goto ( xt -- )  in-slot? if  0 self-frames !  restart  else  execute  then ;
: goto-action ( id -- )  script-for ?dup if  goto  then ;
: call-action ( id -- )  script-for ?dup if  execute  then ;

\ ---- characters: where they are ----
: self-is? ( id -- flag )
    dup $FE = if  drop false exit  then   \ (the active stalker: H3)
    ctx-id @ = ;
: char-here? ( id -- flag )  char-slot char-here ;
: char-busy? ( who -- flag )   \ (a scene's slot running, or a character in a scripted action)
    dup scene-id? if  slot-of slot-task @ 0<> exit  then
    char-slot dup 0< if  drop false exit  then  cells char-scripted + @ 0<> ;
: char-in-area? ( who area -- flag )
    swap char-slot dup char-here 0= if  2drop false exit  then  swap char-in-area ;
: char-entered-area? ( who area -- flag )
    swap char-slot dup char-here 0= if  2drop false exit  then  swap char-cross 1 = ;
: char-left-area? ( who area -- flag )
    swap char-slot dup char-here 0= if  2drop false exit  then  swap char-cross -1 = ;
: char-on-tri? ( who tri -- flag )
    swap char-slot dup char-here 0= if  2drop false exit  then  char-actor body-tri = ;
: char-in-room? ( who room -- flag )
    swap char-slot dup 0< if  2drop false exit  then  char-actor dup 0< if  2drop false exit  then  body-room = ;
\ faces heading dir x 2 degrees (a signed byte), within `within` degrees
: char-heading? ( who dir within -- flag )
    rot char-slot dup char-here 0= if  drop 2drop false exit  then
    char-actor body-yaw angle-wrap deg  swap $FF and dup $80 and if  $100 -  then  2* s>f f-  fabs
    fdup 180e f> if  360e fswap f-  then  s>f f<= ;

\ ---- exits (cmd_exit, Progress_ExitOpen / ExitPassable) ----
: exit-door ( exit -- door | -1 )  this-room @ swap room-exit-door ;
: door-state ( door -- w )  4 * progress pr.doors + l@ ;
: exit-open ( exit -- flag )   \ a doorway, or a door not locked with its open bit
    exit-door dup 0< if  drop false exit  then
    dup door-flags 1 and if  drop true exit  then
    door-state dup 8 and if  drop false exit  then  2 and 0<> ;
: exit-passable ( exit -- flag )  exit-door dup 0< if  drop false exit  then  door-state $10 and 0= ;
\ take exit `exit` after this frame (bit 7: whatever its door; else if it is open to whoever is
\ controlled - Fiona, free of scripts)
: exit-check ( exit -- )
    dup $80 and if  $7F and dup exit-taken !  going !  -1 leaving !  exit  then
    dup exit-door dup 0< 0= if  door-locked? if  drop exit  then  else  drop  then
    dup exit-passable 0= if  drop exit  then
    0 cells char-scripted + @ if  drop exit  then
    dup exit-taken !  going ! ;
: exit-prepare ( exit -- )  drop ;   \ (the next room loaded ahead: rooms come in at once here)
: exit-usable? ( exit -- flag )   \ Fiona free (no script, moving on her own or 0xA), in the exit's
    0 cells char-scripted + @ if  drop false exit  then          \ area, its door open and not held
    fiona-mode @ dup 0<> swap $A <> and if  drop false exit  then
    0 char-here 0= if  drop false exit  then
    0 over exit-area char-in-area 0= if  drop false exit  then
    dup exit-open 0= if  drop false exit  then
    exit-door door-held? 0= ;
: exit-taken? ( exit -- flag )  exit-taken @ = ;
: exit-door-open? ( exit -- flag )  exit-open ;
\ a character put on the exit's outside spot, facing in (Rooms_ExitPointOut)
: char-to-exit ( who exit -- )
