\ story/words.fs - the words the rooms' event scripts are written in (docs/subsystems/story.md):
\ one per command and condition of the original bytecode (the old new-src's events/words.fs has
\ the reference meanings; docs/event_opcodes.md the opcodes). The scripts run as their room's
\ actor: what they change of the room is its fields; what they ask of others goes as messages;
\ what they read of others are facts (bodies, the progress, the nav mesh) or what they were told.
\
\ Written so far: flags and variables, the script context and its waits, actions, characters
\ in areas and on triangles, exits, the camera, doors, the nav mesh's groups, sounds. The rest
\ is at the end (generated by tools/story_stubs.py): each says once that it isn't written yet
\ and does nothing (a condition: false).
IN: story.words
USING: engine game-state actors messages common keys doors obstacles room-names flag-names story-names story.state story.strings effects items ;

\ ---- the registered scripts (data: each room's phases and actions, the shared ones) ----
$110 constant #rooms
create room-scripts    #rooms 7 * cells allot     room-scripts #rooms 7 * cells 0 fill
create action-scripts  #rooms $80 * cells allot   action-scripts #rooms $80 * cells 0 fill
create shared-scripts  $80 cells allot            shared-scripts $80 cells 0 fill
\ phases: 0 entering, 1 / 2 each frame (before / after the commands), 3 each frame's end, 4
\ leaving, 5 left (the next room in), 6 a character entering
: room-script ( room phase -- addr )  swap 7 * + cells room-scripts + ;
: action-script ( room id -- addr )  swap $80 * + cells action-scripts + ;
: room-script! ( xt room phase -- )  room-script ! ;
: action-script! ( xt room id -- )  action-script ! ;
: builtin-script! ( xt id -- )  $80 - cells shared-scripts + ! ;
: script-for ( act -- xt | 0 )   \ (an action of this room, or a shared one from 0x80)
    dup $80 < if  this-room @ swap action-script @  else  $80 - $7F and cells shared-scripts + @  then ;

\ ---- not written yet: said once a word, then nothing ----
create missing 16 1024 * allot  variable #missing
: place ( addr len dest -- )  2dup c!  1+ swap move ;   \ (a counted string)
: cstring ( addr -- addr' len )  dup 1+ swap c@ ;
: missing? ( addr len -- flag )
    #missing @ 0 ?do  2dup missing i 32 * + cstring compare 0= if  2drop true unloop exit  then  loop  2drop false ;
: stub-step ( addr len -- )
    2dup missing? if  2drop exit  then
    #missing @ 512 < if  2dup 31 min missing #missing @ 32 * + place  1 #missing +!  then
    ." story: " type ."  - not written yet" cr ;
: stub-flag ( addr len -- flag )  stub-step false ;
: .missing ( -- )  #missing @ 0 ?do  missing i 32 * + cstring type space  loop  cr ;

\ ---- small things ----
: bit ( n addr -- mask addr' )  over 5 rshift 4 * +  swap 31 and 1 swap lshift swap ;
: bit? ( n addr -- flag )  bit l@ and 0<> ;
: bit-on ( n addr -- )  bit dup l@ rot or swap l! ;
: bit-off ( n addr -- )  bit dup l@ rot invert and swap l! ;
: deg ( F: a -- d )  180e f* pi f/ ;
: b0 ( -- ) ;   : b1 ( -- ) ;   : b2 ( -- ) ;   : b3 ( -- ) ;   : b4 ( -- ) ;   \ (the converter's byte markers)

\ ---- the script running now ----
: in-slot? ( -- flag )  ctx-slot @ 0< 0= ;
: self-char ( -- cs )  ctx-who @ ;
: self-frames ( -- addr )  in-slot? if  ctx-slot @ cells slot-frames +  else  phase-frames  then ;
: wait-frame ( -- )  in-slot? if  yield  then ;
: wait-until ( xt -- )   \ (a phase script can't wait: it looks once)
    in-slot? 0= if  drop exit  then  begin  dup execute 0= while  yield  repeat  drop ;

\ ---- the characters, by the scripts' slots (0 Fiona, 1 Hewie; the others with the stalkers) ----
: fiona-id ( -- id )  s" fiona" actor-named ;
: hewie-id ( -- id )  s" hewie" actor-named ;
\ the stalker's slot (the story's character slot 2, `$FE` in the scripts): the stalker actor
\ partner-load brought in (the original's progress character table), -1 none
variable slot2   -1 slot2 !
variable slot2-kind   -1 slot2-kind !    \ (the kind partner-load put there: its +0x153C)
: cast-actor ( slot -- id | -1 )   \ the event characters' figures (slots 3..5: cast.fs)
    case  3 of  s" cast3"  endof  4 of  s" cast4"  endof  5 of  s" cast5"  endof  >r 0 0 r>  endcase
    dup if  actor-named  else  2drop -1  then ;
\ the story's character slots 2..5: the actor in each (the stalkers by kind, the figures) and the
\ character's script id in it (the original's progress character table)
create slot-actors  -1 , -1 , -1 , -1 , -1 , -1 ,
create slot-chars  -1 , -1 , -1 , -1 , -1 , -1 ,
: slot-actor ( slot -- addr )  cells slot-actors + ;
: slot-id ( slot -- addr )  cells slot-chars + ;
: slot-actor-of ( cs -- id | -1 )   \ whoever is in the slot, placed or not
    case
        0 of  fiona-id  endof
        1 of  hewie-id  endof
        2 of  slot2 @  endof
        dup 3 6 within if  dup slot-actor @  else  -1  then  swap
    endcase ;
: char-actor ( cs -- id | -1 )
    case
        0 of  fiona-id  endof
        1 of  hewie-id  endof
        2 of  slot2 @  endof   \ (the stalker's slot: whoever partner-load put there)
        dup 3 6 within if  dup slot-actor @  else  -1  then  swap
    endcase  dup 0< if  exit  then  dup body? 0= if  drop -1  then ;
\ a script id to a slot: 0 Fiona, 1 Hewie, 0xFF the script's own, the stalker $FE, the others by
\ the slot they were loaded into (Progress_SlotOfId; -1: nobody)
: char-slot ( id -- cs | -1 )
    dup $FF = if  drop self-char exit  then
    dup $FE = if  drop 2 exit  then   \ (the stalker)
    dup 0 2 within if  exit  then
    6 3 do  i slot-id @ over = if  drop i unloop exit  then  loop  drop -1 ;
: char-here ( cs -- flag )   \ in the game and in this room
    dup 0< if  drop false exit  then  char-actor dup 0< if  drop false exit  then  body-room this-room @ = ;
: in-room? ( cs -- flag )  char-here ;
: char-at ( cs -- v )  char-actor body-at ;
: char-was ( cs -- v )  12 * char-was + ;
: char-in-area ( cs area -- flag )  swap char-at vec@ area-in? ;
\ crossing an area since the last frame: 1 into it, -1 out of it, 0 neither
: char-cross ( cs area -- n )
    over cells char-seen + @ 0= if  2drop 0 exit  then
    >r dup char-was vec@ char-at vec@ r> area-cross ;
\ (each frame's end: where they are, for the next frame's crossings)
: remember-chars ( -- )
    #chars 0 do
        i char-here if  i char-was i char-at vec-copy  -1 i cells char-seen + !
        else  0 i cells char-seen + !  then
    loop ;
: who>cs ( who -- cs | -1 )   \ (a character argument: 0xFF self)
    dup $FF = if  drop self-char  else  char-slot  then ;

