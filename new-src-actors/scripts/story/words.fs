    char-actor dup 0< if  drop 2drop exit  then  -rot camera-id send camera-setup ;
: char-camera ( id set path -- )  rot char-slot -rot char-cam! ;
: camera-follow ( id -- )
    dup $FF = if  drop $FF camera-char !  -1 camera-id send follow exit  then
