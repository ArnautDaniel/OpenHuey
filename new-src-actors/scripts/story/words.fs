: game-mode? ( mode -- flag )  the-danger @ = ;
: panic-stage? ( stage -- flag )   \ (0xFF: panicking, 4 or 5)
    dup $FF = if  drop the-panic @ 4 6 within  else  the-panic @ =  then ;
