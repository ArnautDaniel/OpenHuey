    rot who>cs dup 0< if  drop 2drop exit  then                ( tri face cs )
    rot tri-center fdrop at-y f! fdrop
    at-x f@ at-y f@ at-z f@  swap s>f deg>rad  place-char ;
: char-to-xyz ( who face F: x y z -- )
