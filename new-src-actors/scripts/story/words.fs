: cast-actor ( slot -- id | -1 )   \ the event characters' figures (cast.fs), by their slot
    figure-actor-name dup if  actor-named  else  2drop -1  then ;
\ the story's character slots: the actor in each (the stalkers by kind, the figures) and the
\ character's script id in it (the original's progress character table)
create slot-actors  #chars cells allot  slot-actors #chars cells -1 fill
create slot-chars  #chars cells allot  slot-chars #chars cells -1 fill
: slot-actor ( slot -- addr )  cells slot-actors + ;
: slot-id ( slot -- addr )  cells slot-chars + ;
: slot-actor-of ( cs -- id | -1 )   \ whoever is in the slot, placed or not
    case
        fiona-cs of  fiona-id  endof
        hewie-cs of  hewie-id  endof
        stalker-cs of  slot2 @  endof   \ (whoever partner-load put there)
        dup figure-cs? if  dup slot-actor @  else  -1  then  swap
    endcase ;
: char-actor ( cs -- id | -1 )   \ (in the game: a body)
    slot-actor-of  dup 0< if  exit  then  dup body? 0= if  drop -1  then ;
\ a script id to a slot: Fiona, Hewie, the script's own, the stalker, the others by the slot they
\ were loaded into (Progress_SlotOfId; -1: nobody)
: char-slot ( id -- cs | -1 )
    dup self-who = if  drop self-char exit  then
    dup stalker-who = if  drop stalker-cs exit  then
    dup fiona-cs stalker-cs within if  exit  then
    #chars first-figure-cs do  i slot-id @ over = if  drop i unloop exit  then  loop  drop -1 ;
: char-here ( cs -- flag )   \ in the game and in this room
    dup 0< if  drop false exit  then  char-actor dup 0< if  drop false exit  then  body-room this-room @ = ;
: in-room? ( cs -- flag )  char-here ;
: char-at ( cs -- v )  char-actor body-at ;
: char-was ( cs -- v )  /vec * char-was + ;
: char-in-area ( cs area -- flag )  swap char-at vec@ area-in? ;
\ crossing an area since the last frame: 1 into it, -1 out of it, 0 neither
: char-cross ( cs area -- n )
    over cells char-seen + @ 0= if  2drop 0 exit  then
    >r dup char-was vec@ char-at vec@ r> area-cross ;
\ (each frame's end: where they are, for the next frame's crossings)
: remember-chars ( -- )
    #chars 0 do
        i char-here if  i char-was i char-at vec-copy  -1 i cells char-seen + !
        else  0 i cells char-seen + !  then
    loop ;
: who>cs ( who -- cs | -1 )   \ (a character argument: self-who its own)
    dup self-who = if  drop self-char  else  char-slot  then ;

