\ story/words.fs - the words the rooms' event scripts are written in (docs/subsystems/story.md):
\ one per command and condition of the original bytecode (the old new-src's events/words.fs has
\ the reference meanings; docs/event_opcodes.md the opcodes). The scripts run as their room's
\ actor: what they change of the room is its fields; what they ask of others goes as messages;
\ what they read of others are facts (bodies, the progress, the nav mesh) or what they were told.
\
\ Written so far: flags and variables, the script context and its waits, actions, characters
\ in areas and on triangles, exits, the camera, doors, the nav mesh's groups, sounds. The rest
\ is at the end (generated by tools/story_stubs.py): each says once that it isn't written yet
\ and does nothing (a condition: false).
IN: story.words
USING: engine game-state actors messages common keys vectors doors obstacles room-names flag-names story-names stalker-names hewie-names story.state story.strings effects items items.names ;

\ ---- the registered scripts (data: each room's phases and actions, the shared ones) ----
$110 constant #rooms
$80 constant first-shared   \ (action ids: a room's own below, the shared ones from here)
create room-scripts    #rooms #phases * cells allot     room-scripts #rooms #phases * cells 0 fill
create action-scripts  #rooms first-shared * cells allot   action-scripts #rooms first-shared * cells 0 fill
create shared-scripts  first-shared cells allot            shared-scripts first-shared cells 0 fill
\ (phase#: entering, each frame before / after the commands, the frame's end, leaving, left, a
\ character entering)
: room-script ( room phase -- addr )  swap #phases * + cells room-scripts + ;
: action-script ( room id -- addr )  swap first-shared * + cells action-scripts + ;
: room-script! ( xt room phase -- )  room-script ! ;
: action-script! ( xt room id -- )  action-script ! ;
: shared-script ( id -- addr )  first-shared - first-shared 1- and cells shared-scripts + ;
: builtin-script! ( xt id -- )  shared-script ! ;
\ ---- a room's scripts registered by their names: <room>.enter, .phase1 .. .phase5,
\ .char-enter for its phases, <room>.act00 .. .act7F for its actions; the shared ones
\ shared.act80 .. ----
strings: phase-suffix  enter phase1 phase2 phase3 phase4 phase5 char-enter ;
create script-name 40 allot  variable #script-name
: name+ ( addr len -- )  tuck  script-name #script-name @ + swap move  #script-name +! ;
: hex-digit ( n -- c )  $F and  dup 10 < if  [char] 0  else  [char] A 10 -  then  + ;
: hex2+ ( n -- )  dup 4 rshift hex-digit script-name #script-name @ + c!  hex-digit script-name #script-name @ 1+ + c!
    2 #script-name +! ;
: script-named ( addr len suffix-addr suffix-len -- xt | 0 )   \ the word <addr len>.<suffix>, if defined
    2swap  0 #script-name !  name+  s" ." name+  name+  script-name #script-name @ find-word ;
: act-named ( addr len act -- xt | 0 )
    >r  0 #script-name !  name+  s" .act" name+  r> hex2+  script-name #script-name @ find-word ;
: register-scripts ( room -- )   \ the room's phases and actions, each defined
    {: room | a n :}  room room-name to n to a
    #phases 0 do  a n i phase-suffix script-named ?dup if  room i room-script!  then  loop
    first-shared 0 do  a n i act-named ?dup if  room i action-script!  then  loop ;
: register-shared ( -- )   \ shared.act80 ..
    $100 first-shared do  s" shared" i act-named ?dup if  i builtin-script!  then  loop ;
: script-for ( act -- xt | 0 )   \ (an action of this room, or a shared one)
    dup first-shared < if  this-room @ swap action-script @  else  shared-script @  then ;

\ ---- not written yet: said once a word, then nothing ----
32 constant /missing   512 constant most-missing   \ (each name kept as a counted string)
create missing  most-missing /missing * allot  variable #missing
: place ( addr len dest -- )  2dup c!  1+ swap move ;   \ (a counted string)
: cstring ( addr -- addr' len )  dup 1+ swap c@ ;
: missing# ( i -- addr )  /missing * missing + ;
: missing? ( addr len -- flag )
    #missing @ 0 ?do  2dup i missing# cstring compare 0= if  2drop true unloop exit  then  loop  2drop false ;
: stub-step ( addr len -- )
    2dup missing? if  2drop exit  then
    #missing @ most-missing < if  2dup /missing 1- min #missing @ missing# place  1 #missing +!  then
    ." story: " type ."  - not written yet" cr ;
: stub-flag ( addr len -- flag )  stub-step false ;
: .missing ( -- )  #missing @ 0 ?do  i missing# cstring type space  loop  cr ;

