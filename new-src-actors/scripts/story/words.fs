\ a character moved by (dx, dy, dz), its heading kept (the rooms' commands moving one directly:
\ off the floor and through walls)
create shift-at 12 allot  fvariable shift-yaw
: char-shift ( who F: dx dy dz -- )
    who>cs dup 0< if  drop fdrop fdrop fdrop exit  then
    dup char-here 0= if  drop fdrop fdrop fdrop exit  then
    dup char-at shift-at vec-copy
    shift-at 8 + dup sf@ f+ sf!  shift-at 4 + dup sf@ f+ sf!  shift-at dup sf@ f+ sf!
    dup char-actor body-yaw shift-yaw f!  shift-at vec@ shift-yaw f@  place-char ;
\ room_nudge: b0 0 a 90-frame count started; else character $E lifted dy and on 3 in z each frame
\ till it runs out
