#!/usr/bin/env python3
"""The extras room's galleries' tables from the executable into scripts/subscreen/gallery-tables.fs
(src/game/subscreen.c): the movies' seen flags, the music's tracks, the art's flags, the TYPE
entries and the model gallery's entries (files, motions, camera).

usage: gallerytables.py [repo root]"""
import os
import struct
import sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..')
elf = open(os.path.join(root, 'baserom', 'SLUS_210.75'), 'rb').read()
e_phoff, = struct.unpack_from('<I', elf, 0x1C)
e_phnum, = struct.unpack_from('<H', elf, 0x2C)
segs = [struct.unpack_from('<5I', elf, e_phoff + i * 32)[1:] for i in range(e_phnum)]


def at(va, n):
    for off, vaddr, _, filesz in segs:
        if vaddr <= va and va + n <= vaddr + filesz:
            return elf[off + va - vaddr: off + va - vaddr + n]
    if 0x47B200 <= va < 0x47B200 + 0x10000:   # (the zeroed data, past the file's: _fbss)
        return bytes(n)
    raise ValueError(hex(va))


def u8s(va, n):
    return list(at(va, n))


def u16s(va, n):
    return list(struct.unpack('<%dH' % n, at(va, n * 2)))


def u32s(va, n):
    return list(struct.unpack('<%dI' % n, at(va, n * 4)))


def f32s(va, n):
    return list(struct.unpack('<%df' % n, at(va, n * 4)))


def cstr(va):
    if va == 0:
        return ''
    out = b''
    while True:
        c = at(va + len(out), 1)
        if c == b'\0':
            return out.decode('ascii').replace('\\', '/')
        out += c


def hexes(xs):
    return ' '.join('$%X ,' % x for x in xs)


def floats(xs):
    return ' '.join('%se f,' % repr(round(x, 6)) for x in xs)


ENTRIES = 32
lines = ["\\ Generated by openhuey-src/tools/gallerytables.py from the executable: the extras room's",
         "\\ galleries' tables (src/game/subscreen.c).",
         'IN: subscreen.gallery-tables', '']

# the movies: each one's seen flag (a system data bit, +0x24 on)
movies = u8s(0x44B730, 0x6E)
lines += ['\\ the movies (D_0044B730): each one\'s seen flag (the system data\'s bits from +0x24)',
          '$6E constant #movies', 'create movie-flags ' + ' '.join('$%X c,' % x for x in movies), '']

# the music: per track its unlock flag, its title (a menu message), its BGM number
music = [struct.unpack('<HHBB', at(0x44BF30 + i * 6, 6)) for i in range(27)]
lines += ['\\ the music (D_0044BF30): per track its unlock flag, its title (a menu message) and its BGM',
          '27 constant #tracks', 'create tracks']
lines += ['    %s' % hexes(t[:3]) for t in music]
lines += ['']

# the art: each picture's unlock flag
art = u16s(0x44BFE0, 48)
lines += ['\\ the art (D_0044BFE0): each picture\'s unlock flag', '48 constant #pictures',
          'create picture-flags ' + hexes(art), '']

# the TYPE entries: unlock flag, title, its question, the message after (0xFFFF none)
types = [u16s(0x44C080 + i * 8, 4) for i in range(11)]
groups = u8s(0x47B180, 4)
lines += ['\\ the TYPE entries (kExtraUnlocks): per entry its unlock flag, its title, its message and the',
          '\\ one to follow ($FFFF none); their two groups (D_0047B180: first, end)', '11 constant #types',
          'create types']
lines += ['    %s' % hexes(t) for t in types]
lines += ['create type-groups ' + hexes(groups), '']

# the model gallery
names = lambda va: [cstr(p) for p in u32s(va, ENTRIES)]
pck, tex, tex2, mrk = names(0x44B7B0), names(0x44B830), names(0x44B8B0), names(0x44B930)
counts = u8s(0x44BF10, ENTRIES)
motion_ptrs = u32s(0x44BE90, ENTRIES)
motions = [u32s(p, c) if p else [] for p, c in zip(motion_ptrs, counts)]
dist = f32s(0x44BB70, ENTRIES)
heights = [f32s(0x44B9F0 + i * 12, 3) for i in range(ENTRIES)]
lines += ['\\ the model gallery: per entry its model, textures (a second set: "" none), marker file ("" none)',
          '\\ (D_0044B7B0, D_0044B830, pstr_O_FIN_FIN_200, D_0044B930), its motions (kGalleryMotions,',
          '\\ D_0044BF10: their count), the camera\'s nearest (kGalleryCameraDistance) and its height:',
          '\\ lowest, start, highest (D_0044B9F0 / F4 / F8)',
          '%d constant #models' % ENTRIES]
lines += [': model-files ( i -- pck len tex len tex2 len mrk len )', '    case']
for i in range(ENTRIES):
    lines.append('        %d of  s" %s" s" %s" s" %s" s" %s"  endof' % (i, pck[i], tex[i], tex2[i], mrk[i]))
lines += ['        >r  s" " s" " s" " s" "  r>', '    endcase ;']
lines += ['create model-motions   \\ (each entry\'s: their count, then its motions)']
for m in motions:
    lines.append('    %d , %s' % (len(m), hexes(m)))
starts, k = [], 0
for m in motions:
    starts.append(k)
    k += 1 + len(m)
lines += ['create model-motion-at ' + ' '.join('%d ,' % x for x in starts) + '   \\ (where each entry\'s are, in cells)']
lines += ['create model-nearest ' + floats(dist)]
lines += ['create model-heights']
lines += ['    %s' % floats(h) for h in heights]
lines += ['']

out = os.path.join(root, 'openhuey-src', 'scripts', 'subscreen', 'gallery-tables.fs')
open(out, 'w').write('\n'.join(lines))
print('wrote', out)
