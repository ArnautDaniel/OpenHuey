#!/usr/bin/env python3
"""The sub screen's art from the executable into scripts/subscreen/tables.fs (src/game/subscreen.c
SubScreen_DrawPanel / DrawPart): its panels (SUBSCR/SUBBACK.TEX, the texture cache's group $19:
texture, u, v, w, h, x, y in the 512 x 448 screen), its parts (SUBSCR/SUBBASE.TEX, group $18:
u, v, w, h, the size drawn, palette, texture, blending) and the panels each page shows
(kSubScreenFadePanels).

usage: subscreentables.py [repo root]"""
import os
import re
import struct
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..')
elf = open(os.path.join(root, 'baserom', 'SLUS_210.75'), 'rb').read()
ph, = struct.unpack_from('<I', elf, 0x1C)
n, = struct.unpack_from('<H', elf, 0x2C)
segs = [struct.unpack_from('<5I', elf, ph + i * 32)[1:] for i in range(n)]
syms = {}
for line in open(os.path.join(root, 'config', 'symbol_addrs.txt')):
    m = re.match(r'(\w+) = 0x([0-9A-Fa-f]+);', line)
    if m:
        syms[m.group(1)] = int(m.group(2), 16)


def rd(va, fmt):
    for off, vaddr, _, size in segs:
        if vaddr <= va < vaddr + size:
            return struct.unpack_from(fmt, elf, off + va - vaddr)[0]
    raise ValueError(hex(va))


PANELS, PARTS, KINDS = 20, 43, 16
out = []
w = out.append
w('\\ subscreen/tables.fs - generated by tools/subscreentables.py: the sub screen\'s art from the')
w('\\ executable (src/game/subscreen.c). Panels: texture (of SUBBACK, group $19), u, v, w, h, x, y')
w('\\ (the 512 x 448 screen). Parts: u, v, w, h, the size drawn, palette, texture (of SUBBASE, group')
w('\\ $18; 15 the item\'s picture), blending (0 plain, 1..3 the fixed alphas). Pages: the panels each')
w('\\ page shows (-1 none).')
w('IN: subscreen.tables')
w('USING: engine ;')
w('')
w('7 cells constant /panel')
w('create panels')
for k in range(PANELS):
    w('  ' + '  '.join('%d ,' % rd(0x44C160 + k * 14 + i * 2, '<H') for i in range(7)) + '   \\ %d' % k)
w('9 cells constant /part')
w('create parts')
for k in range(PARTS):
    w('  ' + '  '.join('%d ,' % rd(0x44C280 + k * 18 + i * 2, '<H') for i in range(9)) + '   \\ %d' % k)
w('create page-panels')
for k in range(KINDS):
    w('  ' + '  '.join('%d ,' % rd(syms['kSubScreenFadePanels'] + k * 4 + i, '<b') for i in range(4)) + '   \\ %d' % k)


def cstr(va):
    b = b''
    while rd(va, '<B'):
        b += bytes([rd(va, '<B')])
        va += 1
    return b.decode('latin1')


# the maps (Map_FindRoom, Map_PageFrame, Map_HereArrow: kMapRooms, kMapPages, the titles)
w('')
w('\\ the maps: per map its pages (the picture\'s file, its title: a message of the second table)')
w('\\ and its rooms (room, page, x and z scale, x and y offset of the arrow on the page)')
maps = []
m = 0
while rd(syms['kMapRooms'] + m * 4, '<I') or rd(syms['kMapPages'] + m * 4, '<I'):
    r, p = rd(syms['kMapRooms'] + m * 4, '<I'), rd(syms['kMapPages'] + m * 4, '<I')
    t = rd(0x41F8B0 + m * 4, '<I')
    pages = []
    while p and rd(p + len(pages) * 4, '<I'):
        pages.append(cstr(rd(p + len(pages) * 4, '<I')))
    titles = [rd(t + i * 2, '<H') for i in range(len(pages))]
    rooms = []
    while r and rd(r + len(rooms) * 0x18, '<i') != -1:
        e = r + len(rooms) * 0x18
        rooms.append((rd(e, '<i'), rd(e + 4, '<b'), rd(e + 8, '<f'), rd(e + 12, '<f'), rd(e + 16, '<f'), rd(e + 20, '<f')))
    maps.append((pages, titles, rooms, r))
    m += 1
w('%d constant #maps' % len(maps))
for k, (pages, titles, rooms, table) in enumerate(maps):
    w(': map%d-page ( page -- addr len title )' % k)
    w('    case')
    for i, (f, t) in enumerate(zip(pages, titles)):
        w('        %d of  s" %s"  $%X  endof' % (i, f[:-4].replace('\\', '/'), t))
    w('        >r 0 0 0 r>')
    w('    endcase ;')
    w('create map%d-rooms   \\ (room page | x-scale z-scale x-off y-off; -1 ends)' % k)
    for (room, page, xs, zs, xo, yo) in rooms:
        w('    $%X , %d , %se f, %se f, %se f, %se f,' % (room, page, repr(xs), repr(zs), repr(xo), repr(yo)))
    w('    -1 ,')
    if k == 2:   # (Map_HereArrow: the maze rooms' three spots, entries 14..16 of the forest's table)
        w("\\ (the maze rooms' three spots, by their place in the dealt row: D_00420570's entries 14..16)")
        w('create maze-spots')
        for i in range(14, 17):
            e = table + i * 0x18
            w('    -1 , 0 , %se f, %se f, %se f, %se f,' % tuple(repr(rd(e + o, '<f')) for o in (8, 12, 16, 20)))
w(': map-page ( map page -- addr len title )   \\ (0 0 0: no such page)')
w('    swap case')
for k in range(len(maps)):
    w('        %d of  map%d-page  endof' % (k, k))
w('        >r drop 0 0 0 r>')
w('    endcase ;')
w(': map-pages ( map -- n )  case')
for k, (pages, _, _, _) in enumerate(maps):
    w('        %d of  %d  endof' % (k, len(pages)))
w('        >r 0 r>  endcase ;')
w(': map-rooms ( map -- addr | 0 )  case')
for k in range(len(maps)):
    w('        %d of  map%d-rooms  endof' % (k, k))
w('        >r 0 r>  endcase ;')

# the slot machine (items.c SlotMachine_*, sy_finish: D_00460430.. kSlotReelsPicked)
w('')
w('\\ the slot machine (the synthesizer, mode 3): the reels (35 symbols: 0..3 the four kinds, 4 a')
w('\\ blank, 5 the wild one); per medallion (items $70..$75) the chances of each reel and of the')
w('\\ first row\'s symbol; the 22 cells (the two rows each compares); the results (8 items, -1 none, and')
w('\\ the amounts\' row); the amounts by how many matched (8+, 6+, 4+, 1+); where the rows and cells are')
w('\\ drawn (SYN_SLOT\'s texture 4) and the order the cells are drawn in')
picked = [rd(syms['kSlotReelsPicked'] + i, '<B') for i in range(11)]
nreel = max(picked) + 1
w('create reels')
for r in range(nreel):
    w('    ' + ' '.join('%d ,' % rd(0x460430 + r * 35 + i, '<B') for i in range(35)))
w('create reels-picked  ' + ' '.join('%d ,' % v for v in picked))
w('create reel-chances')
for m in range(6):
    w('    ' + ' '.join('%d ,' % rd(0x4605C0 + m * 11 + i, '<B') for i in range(11)))
w('create first-chances')
for m in range(6):
    w('    ' + ' '.join('%d ,' % rd(0x460620 + m * 6 + i, '<B') for i in range(6)))
w('create cell-rows  ' + ' '.join('%d , %d ,' % (rd(0x460650 + c * 2, '<B'), rd(0x460650 + c * 2 + 1, '<B')) for c in range(22)))
w('create results')
for r in range(17):
    w('    ' + ' '.join('%d ,' % rd(0x460680 + (r * 9 + i) * 4, '<i') for i in range(9)))
w('create amounts  ' + ' '.join('%d ,' % rd(0x460A18 + i, '<b') for i in range(12)))
w('create row-places  ' + ' '.join('%d , %d ,' % (rd(0x4608F0 + i * 4, '<h'), rd(0x4608F0 + i * 4 + 2, '<h')) for i in range(10)))
w('create cell-draws   \\ (u v w h x y, flipped up-down, flipped left-right)')
for c in range(22):
    e = 0x460920 + c * 10
    w('    ' + ' '.join('%d ,' % v for v in [rd(e + i, '<B') for i in range(4)] + [rd(e + 4, '<h'), rd(e + 6, '<h'), rd(e + 8, '<B'), rd(e + 9, '<B')]))
w('create cell-order  ' + ' '.join('%d ,' % rd(0x460A00 + i, '<B') for i in range(22)))
path = os.path.join(here, '..', 'scripts', 'subscreen', 'tables.fs')
os.makedirs(os.path.dirname(path), exist_ok=True)
open(path, 'w').write('\n'.join(out) + '\n')
print('wrote', path)
